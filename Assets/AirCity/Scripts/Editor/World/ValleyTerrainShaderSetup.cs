using System;
using System.IO;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEngine;

namespace AirCity.EditorTools.World
{
    /// <summary>Rebases a small sampling extension onto the installed URP terrain implementation.</summary>
    public static class ValleyTerrainShaderSetup
    {
        public const string ShaderPath = "Assets/AirCity/Shaders/ValleyTerrain.shader";
        const string Root = "Assets/AirCity/Shaders/";
        const string Package = "Packages/com.unity.render-pipelines.universal/Shaders/Terrain/";
        const string Notice = "// Generated by ValleyTerrainShaderSetup from the installed Unity URP Terrain/Lit implementation.\n" +
            "// com.unity.render-pipelines.universal copyright (c) 2020 Unity Technologies ApS.\n" +
            "// Licensed under the Unity Companion License for Unity-dependent projects.\n" +
            "// See ValleyTerrain-Unity-LICENSE.txt. AirCity adds layer sampling and world-space cliff surfacing.\n";
        static bool importsReady;

        [MenuItem("AirCity/World/Regenerate Terrain Shader")]
        public static void Regenerate() { importsReady = false; Ensure(); }

        public static Shader Ensure()
        {
            var package = UnityEditor.PackageManager.PackageInfo.FindForAssetPath(Package + "TerrainLit.shader");
            if (package == null) throw new InvalidOperationException("The installed URP terrain source could not be located.");
            string sourceRoot = Path.Combine(package.resolvedPath, "Shaders/Terrain");
            // Register include assets and hidden dependencies before the main shader. Unity resolves terrain
            // dependencies by Shader name; a broad Refresh can otherwise import the main asset first.
            string[] files = { "TerrainLitInput.hlsl", "TerrainLitPasses.hlsl", "TerrainLitDepthNormalsPass.hlsl",
                "TerrainLitAdd.shader", "TerrainLitBasemapGen.shader", "TerrainLitBase.shader", "TerrainLit.shader" };
            bool changed = false;
            foreach (string file in files)
            {
                string text = File.ReadAllText(Path.Combine(sourceRoot, file));
                text = RedirectIncludes(text);
                text = text.Replace("Shader \"Universal Render Pipeline/Terrain/Lit\"", "Shader \"AirCity/ValleyTerrain\"")
                    .Replace("Hidden/Universal Render Pipeline/Terrain/Lit (Add Pass)", "Hidden/AirCity/ValleyTerrain Add")
                    .Replace("Hidden/Universal Render Pipeline/Terrain/Lit (Basemap Gen)", "Hidden/AirCity/ValleyTerrain Basemap Gen")
                    .Replace("Hidden/Universal Render Pipeline/Terrain/Lit (Base Pass)", "Hidden/AirCity/ValleyTerrain Base");
                // Leave control, heightfield, holes and baked base-map sampling exactly as URP defines them.
                text = Regex.Replace(text, @"SAMPLE_TEXTURE2D\((_Splat[0-3]|_Normal[0-3]|_Mask[0-3]),\s*(\w+),\s*([^)]+)\)",
                    m => "ValleySample(TEXTURE2D_ARGS(" + m.Groups[1].Value + ", " + m.Groups[2].Value + "), " + m.Groups[3].Value + ")");
                if (file == "TerrainLitInput.hlsl")
                {
                    text = text.Replace("#define SampleLayerAlbedo(i)", "#include \"Assets/AirCity/Shaders/ValleyTerrainSampling.hlsl\"\n\n#define SampleLayerAlbedo(i)");
                    foreach (string texture in new[] { "_Splat", "_Normal", "_Mask" })
                        text = text.Replace("SAMPLE_TEXTURE2D(" + texture + "##i, sampler_" + texture.Substring(1) + "0, splat##i##uv)",
                            "ValleySample(TEXTURE2D_ARGS(" + texture + "##i, sampler_" + texture.Substring(1) + "0), splat##i##uv)");
                }
                text = SkipUnseenLayers(file, text);
                text = ExtendCliffs(file, text);
                text = ExtendBuiltSurfaces(file,text);
                changed |= Write(Root + file.Replace("TerrainLit", "ValleyTerrain"), Notice + text);
            }
            string license = File.ReadAllText(Path.Combine(package.resolvedPath, "LICENSE.md"));
            changed |= Write(Root + "ValleyTerrain-Unity-LICENSE.txt", license);
            if (!importsReady || changed || AssetDatabase.LoadAssetAtPath<Shader>(ShaderPath) == null)
            {
                const ImportAssetOptions options = ImportAssetOptions.ForceSynchronousImport | ImportAssetOptions.ForceUpdate;
                AssetDatabase.ImportAsset(Root + "ValleyTerrainSampling.hlsl", options);
                AssetDatabase.ImportAsset(Root + "ValleyCliffs.hlsl", options);
                AssetDatabase.ImportAsset(Root + "ValleyBuiltSurfaces.hlsl", options);
                foreach (string file in files)
                {
                    string path = Root + file.Replace("TerrainLit", "ValleyTerrain");
                    AssetDatabase.ImportAsset(path, options);
                    if (file == "TerrainLitAdd.shader" || file == "TerrainLitBasemapGen.shader")
                    {
                        var dependency = AssetDatabase.LoadAssetAtPath<Shader>(path);
                        if (dependency == null || Shader.Find(dependency.name) == null)
                            throw new InvalidOperationException("The terrain dependency shader could not be registered: " + path);
                    }
                }
                importsReady = true;
            }
            return AssetDatabase.LoadAssetAtPath<Shader>(ShaderPath);
        }

        /// <summary>The four layers' lookups are most of the terrain's cost: pass each one its layer's weight at the
        /// pixel, so a layer the pixel does not show is not read. The control map is sampled before the masks.</summary>
        static string SkipUnseenLayers(string file, string text)
        {
            if (file == "TerrainLitPasses.hlsl")
            {
                text = Regex.Replace(text, @"ValleySample\(TEXTURE2D_ARGS\((_Splat|_Normal|_Mask)([0-3]), (\w+)\), ([^)]+)\)",
                    m => "ValleySampleWeighted(TEXTURE2D_ARGS(" + m.Groups[1].Value + m.Groups[2].Value + ", " + m.Groups[3].Value + "), " +
                        m.Groups[4].Value + ", splatControl." + "rgba"[int.Parse(m.Groups[2].Value)] + ")");
                text = ReplaceRequired(text, "void ComputeMasks(out half4 masks[4], half4 hasMask, float4 uvSplat01, float4 uvSplat23)",
                    "// splatControl: the layers' weights at this pixel. Every use of a mask is multiplied by its layer's weight, so a\n" +
                    "// layer without weight is not read.\n" +
                    "void ComputeMasks(out half4 masks[4], half4 hasMask, float4 uvSplat01, float4 uvSplat23, half4 splatControl)");
                const string Masks = "    half4 hasMask = half4(_LayerHasMask0, _LayerHasMask1, _LayerHasMask2, _LayerHasMask3);\n" +
                    "    half4 masks[4];\n    ComputeMasks(masks, hasMask, IN.uvSplat01, IN.uvSplat23);\n\n";
                const string Control = "    float2 splatUV = (IN.uvMainAndLM.xy * (_Control_TexelSize.zw - 1.0f) + 0.5f) * _Control_TexelSize.xy;\n" +
                    "    half4 splatControl = SAMPLE_TEXTURE2D(_Control, sampler_Control, splatUV);\n";
                text = ReplaceRequired(text, Masks + Control, Control + "\n" + Masks.Replace("IN.uvSplat23);\n\n", "IN.uvSplat23, splatControl);\n"));
            }
            if (file == "TerrainLitDepthNormalsPass.hlsl")
                text = ReplaceRequired(text, "ComputeMasks(masks, hasMask, IN.uvSplat01, IN.uvSplat23);",
                    "ComputeMasks(masks, hasMask, IN.uvSplat01, IN.uvSplat23, splatControl);");
            return text;
        }

        static string ExtendCliffs(string file, string text)
        {
            if (file.EndsWith(".shader"))
                text = ReplaceRequired(text, "    Properties\n    {", "    Properties\n    {\n" +
                    "        [HideInInspector] _CliffEnabled(\"Cliff surfacing\", Float) = 0\n" +
                    "        [NoScaleOffset] _CliffAlbedo(\"Cliff rock\", 2D) = \"white\" {}\n" +
                    "        [NoScaleOffset] [Normal] _CliffNormal(\"Cliff normal\", 2D) = \"bump\" {}\n" +
                    "        [NoScaleOffset] _CliffMask(\"Cliff mask\", 2D) = \"white\" {}\n" +
                    "        _CliffTileSize(\"Cliff metres per tile\", Float) = 18\n" +
                    "        _CliffNormalStrength(\"Cliff normal strength\", Float) = 0.65\n" +
                    "        _CliffTint(\"Cliff mineral tint\", Color) = (0.9,0.93,0.95,1)\n");
            if (file == "TerrainLitInput.hlsl")
            {
                text = ReplaceRequired(text, "CBUFFER_START(UnityPerMaterial)", "CBUFFER_START(UnityPerMaterial)\n" +
                    "    half4 _CliffTint;\n    float _CliffEnabled, _CliffTileSize, _CliffNormalStrength;\n");
                text = ReplaceRequired(text, "#include \"Assets/AirCity/Shaders/ValleyTerrainSampling.hlsl\"",
                    "#include \"Assets/AirCity/Shaders/ValleyTerrainSampling.hlsl\"\n#include \"Assets/AirCity/Shaders/ValleyCliffs.hlsl\"");
            }
            if (file == "TerrainLitPasses.hlsl")
                text = ReplaceRequired(text, "    InitializeInputData(IN, normalTS, inputData);",
                    "    InitializeInputData(IN, normalTS, inputData);\n" +
                    "#if !defined(TERRAIN_SPLAT_BASEPASS)\n" +
                    "    ValleyCliffSurface(IN.positionWS, ValleyTerrainGeometricNormal(IN.uvMainAndLM.xy, IN.normal.xyz),\n" +
                    "        albedo, smoothness, occlusion, inputData.normalWS);\n#endif");
            if (file == "TerrainLitDepthNormalsPass.hlsl")
            {
                text = ReplaceRequired(text, "    float4 clipPos                  : SV_POSITION;",
                    "    float3 positionWS               : TEXCOORD7;\n    float4 clipPos                  : SV_POSITION;");
                text = ReplaceRequired(text, "    o.clipPos = attributes.positionCS;",
                    "    o.positionWS = attributes.positionWS;\n    o.clipPos = attributes.positionCS;");
                // The installed URP per-pixel-normal branch has a duplicate local and an unused missing viewDir.
                // Keep it valid when terrain instancing selects that shader variant.
                text = text.Replace("        half3 viewDirWS = IN.viewDir;\n", "");
                text = text.Replace("        half3 normalWS = TransformTangentToWorld(normalTS, half3x3(-tangentWS, cross(normalWS, tangentWS), normalWS));",
                    "        normalWS = TransformTangentToWorld(normalTS, half3x3(-tangentWS, cross(normalWS, tangentWS), normalWS));");
                text = ReplaceRequired(text, "    #if defined(_GBUFFER_NORMALS_OCT)",
                    "    ValleyCliffDepthNormal(IN.positionWS, ValleyTerrainGeometricNormal(IN.uvMainAndLM.xy, IN.normal.xyz), normalWS);\n\n" +
                    "    #if defined(_GBUFFER_NORMALS_OCT)");
            }
            return text;
        }

        static string ExtendBuiltSurfaces(string file,string text)
        {
            if(file.EndsWith(".shader"))
            {
                text=ReplaceRequired(text,"    Properties\n    {","    Properties\n    {\n"+
                    "        [HideInInspector] _AirCitySurfaceEnabled(\"Built surface ownership\", Float) = 0\n"+
                    "        [HideInInspector] _AirCitySurfaceGrid(\"Built surface grid\", Vector) = (0,0,0,0)\n");
                text=text.Replace("#pragma target 2.0","#pragma target 4.5").Replace("#pragma target 3.0","#pragma target 4.5");
            }
            if(file=="TerrainLitInput.hlsl")
            {
                text=ReplaceRequired(text,"CBUFFER_START(UnityPerMaterial)","CBUFFER_START(UnityPerMaterial)\n    float4 _AirCitySurfaceGrid;\n    float _AirCitySurfaceEnabled;");
                text=ReplaceRequired(text,"#include \"Assets/AirCity/Shaders/ValleyCliffs.hlsl\"",
                    "#include \"Assets/AirCity/Shaders/ValleyCliffs.hlsl\"\n#include \"Assets/AirCity/Shaders/ValleyBuiltSurfaces.hlsl\"");
            }
            if(file=="TerrainLitPasses.hlsl")
            {
                // The lit pass discards only after its layer and cliff lookups: those skip unseen layers in dynamic
                // branches, and a discard before such a branch leaves garbage pixels in blocks round every built
                // surface's edge (Metal, Apple GPU).
                text=ReplaceRequired(text,"    InitializeBakedGIData(IN, inputData);","    AirCityClipBuiltSurface(IN.positionWS);\n    InitializeBakedGIData(IN, inputData);");
                text=ReplaceRequired(text,"    float2 texcoord     : TEXCOORD0;","    float2 texcoord     : TEXCOORD0;\n    float3 positionWS   : TEXCOORD1;");
                text=ReplaceRequired(text,"    o.texcoord = v.texcoord;","    o.positionWS = positionWS;\n    o.texcoord = v.texcoord;");
                text=ReplaceRequired(text,"    o.clipPos = TransformObjectToHClip(v.position.xyz);","    float3 positionWS=TransformObjectToWorld(v.position.xyz);\n    o.clipPos = TransformWorldToHClip(positionWS);");
                foreach(string pass in new[]{"ShadowPassFragment","DepthOnlyFragment"})
                    text=ReplaceRequired(text,"half4 "+pass+"(VaryingsLean IN) : SV_TARGET\n{","half4 "+pass+"(VaryingsLean IN) : SV_TARGET\n{\n    AirCityClipBuiltSurface(IN.positionWS);");
            }
            if(file=="TerrainLitDepthNormalsPass.hlsl")
                text=ReplaceRequired(text,"    #ifdef _WRITE_RENDERING_LAYERS\n    outRenderingLayers = EncodeMeshRenderingLayer();",
                    "    AirCityClipBuiltSurface(IN.positionWS);\n\n    #ifdef _WRITE_RENDERING_LAYERS\n    outRenderingLayers = EncodeMeshRenderingLayer();");
            return text;
        }

        static string ReplaceRequired(string text, string before, string after)
        {
            if (!text.Contains(before)) throw new InvalidOperationException("The installed URP terrain source changed at: " + before);
            return text.Replace(before, after);
        }

        static string RedirectIncludes(string text)
        {
            foreach (string name in new[] { "Input", "Passes", "DepthNormalsPass" })
            {
                string original = "TerrainLit" + name + ".hlsl";
                string replacement = Root + "ValleyTerrain" + name + ".hlsl";
                text = text.Replace("\"" + Package + original + "\"", "\"" + replacement + "\"")
                    .Replace("\"" + original + "\"", "\"" + replacement + "\"");
            }
            return text;
        }

        static bool Write(string path, string contents)
        {
            if (File.Exists(path) && File.ReadAllText(path) == contents) return false;
            File.WriteAllText(path, contents); return true;
        }
    }
}
